#!/usr/bin/env python3
"""Encode the two background music tracks into src/music_tracks.js (Ogg Opus, base64 data URLs).
The tracks are rendered by music-lab (github.com/ML-Chen/oct-2026-dump, folder music-lab).
audio.js decodes each track once and loops it gaplessly, so each file gets a short fade-in and a
fade-out that lands on silence, which makes the loop point sound like a soft breath, not a cut.
Usage: python3 tools/make_music.py [/path/to/oct-2026-dump/music-lab]"""
import base64, json, os, subprocess, sys, tempfile

LAB = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'music-lab')
KBPS = 56
# name -> (music-lab demo, seconds to keep or None for all, fade-out seconds)
TRACKS = {
    'title': ('demos/retro/lanternbrook_v2.mp3', None, 3.0),    # Super Nintendo town theme (67 s, has its own ending)
    'results': ('demos/game/hilltop_dash_v2.mp3', None, 1.5),   # NES chiptune (45 s)
}
LIMIT = 4 * 1024 * 1024


def duration(path):
    r = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path],
                       capture_output=True, text=True, check=True)
    return float(r.stdout.strip())


out = {}
m4a = {}  # AAC copies for iPhones and iPads whose Safari can't decode Ogg Opus
with tempfile.TemporaryDirectory() as tmp:
    for name, (rel, keep, fade) in TRACKS.items():
        src = os.path.join(LAB, rel)
        # end of the audible part: the files carry ~1 s of trailing silence, which would leave a gap in the loop
        end = keep or duration(src) - 0.5
        dst = os.path.join(tmp, name + '.ogg')
        af = (f'atrim=0:{end:.2f},loudnorm=I=-18:TP=-2:LRA=11,'
              f'afade=t=in:d=0.05,afade=t=out:st={end - fade:.2f}:d={fade}')
        subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', src, '-af', af, '-c:a', 'libopus', '-b:a', f'{KBPS}k',
                        '-ar', '48000', '-ac', '2', dst], check=True)
        out[name] = 'data:audio/ogg;base64,' + base64.b64encode(open(dst, 'rb').read()).decode()
        dst2 = os.path.join(tmp, name + '.m4a')
        subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', src, '-af', af, '-c:a', 'aac', '-b:a', '64k', '-ar', '44100', '-ac', '2',
                        '-movflags', '+faststart', dst2], check=True)
        m4a[name] = 'data:audio/mp4;base64,' + base64.b64encode(open(dst2, 'rb').read()).decode()
        print(f'{name}: {rel} -> {end:.1f} s, {len(out[name]) // 1024} KB')

js = ('// music_tracks.js — background music rendered with ML-Chen/oct-2026-dump music-lab (Ogg Opus, '
      f'{KBPS} kbps). Generated by tools/make_music.py; do not edit by hand.\n'
      'const MUSIC_TRACKS = ' + json.dumps(out, indent=0) + ';\n'
      'const MUSIC_TRACKS_M4A = ' + json.dumps(m4a, indent=0) + ';\n')
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'music_tracks.js')
open(dst, 'w').write(js)
size = os.path.getsize(dst)
print(f'wrote {os.path.normpath(dst)}: {size / 1024:.0f} KB')
if size > LIMIT:
    sys.exit('music_tracks.js is over the 4 MB budget; set a shorter keep time in TRACKS')
